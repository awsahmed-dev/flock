#!/usr/bin/env node
/**
 * Build src/lib/packages/descriptions.ts from the authored per-region files.
 *
 * WHY THIS EXISTS AS A SEPARATE TABLE, not a field on each place:
 *
 * The `why` line on a curated place is an argument — a reason a person can
 * repeat out loud as their own. It is deliberately written for someone
 * standing in front of the place. What it never does is say what the place
 * IS, and the app's owner hit that wall reading his own plan:
 *
 *   "I don't know what are you talking about because I don't know the
 *    places... So I cannot like trust you enough to say like, yeah, okay,
 *    go with it."
 *
 * So every place also gets a flat, factual identifying sentence. Keeping it
 * in one table rather than inline on 530 objects means the whole corpus can
 * be read top to bottom in one pass and checked for consistency of voice —
 * which is exactly what a line whose only job is to be plain needs.
 *
 * Usage: node scripts/build-descriptions.mjs <dir-of-*.out.json>
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: build-descriptions.mjs <dir>");
  process.exit(1);
}

const files = readdirSync(dir).filter((f) => f.endsWith(".out.json")).sort();
if (!files.length) {
  console.error(`no .out.json files in ${dir}`);
  process.exit(1);
}

const rows = new Map();
const dupes = [];
for (const f of files) {
  const list = JSON.parse(readFileSync(join(dir, f), "utf8"));
  for (const r of list) {
    if (!r?.name || !r?.what || !r?.whatAr) {
      console.error(`  incomplete row in ${f}: ${JSON.stringify(r)?.slice(0, 80)}`);
      continue;
    }
    if (rows.has(r.name)) {
      dupes.push(r.name);
      continue;
    }
    rows.set(r.name, { what: r.what.trim(), whatAr: r.whatAr.trim(), src: f });
  }
  console.log(`  ${f}: ${list.length}`);
}

const sorted = [...rows.entries()].sort(([a], [b]) => a.localeCompare(b));
const esc = (s) => JSON.stringify(s);

const out = `/**
 * The plain sentence that says what a place IS.
 *
 * Generated by scripts/build-descriptions.mjs — edit the source data, or
 * edit here and keep the change; nothing regenerates this without being
 * asked to.
 *
 * Every curated place has one, and a test enforces that. The rule the
 * corpus is held to: state the kind of thing and where it is, and nothing
 * that is not already established by the place's own name, its city, or its
 * \`why\`. No dates, no prices, no counts, no evaluation. A line that reads as
 * dull has done its job — the \`why\` is where the argument lives, and it
 * only lands once the reader knows what they are looking at.
 */

export interface PlaceDescription {
  what: string;
  whatAr: string;
}

export const PLACE_WHAT: Record<string, PlaceDescription> = {
${sorted
  .map(([name, v]) => `  ${esc(name)}: { what: ${esc(v.what)}, whatAr: ${esc(v.whatAr)} },`)
  .join("\n")}
};

/** The description for a place, or null when we have not written one. */
export function whatIs(name: string): PlaceDescription | null {
  return PLACE_WHAT[name] ?? null;
}
`;

const target = "src/lib/packages/descriptions.ts";
writeFileSync(target, out);
console.log(`\nwrote ${target} — ${sorted.length} descriptions`);
if (dupes.length) console.log(`skipped ${dupes.length} duplicate names: ${dupes.slice(0, 5).join(", ")}`);
